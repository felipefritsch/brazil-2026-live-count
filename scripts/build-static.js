// Build the static site into docs/ (served by GitHub Pages): the page, the map shapes,
// the 2022 data, and lib/ bundled into one browser script.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'docs');
fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(path.join(root, 'public'), out, { recursive: true });
fs.mkdirSync(path.join(out, 'data'), { recursive: true });
fs.copyFileSync(path.join(root, 'data', 'pres2022_curve.json'), path.join(out, 'data', 'pres2022_curve.json'));
fs.writeFileSync(path.join(out, '.nojekyll'), '');

const mods = ['tse', 'projection', 'swing', 'core']; // dependency order
const base = fs.readFileSync(path.join(root, 'data', 'base2022.json'), 'utf8');
let js = '// Generated by scripts/build-static.js — do not edit.\n(function () {\nconst __mods = {};\nconst __req = (p) => __mods[p.replace("./", "")];\n';
for (const m of mods) {
  const src = fs.readFileSync(path.join(root, 'lib', `${m}.js`), 'utf8');
  js += `__mods[${JSON.stringify(m)}] = (function (module, require) {\n${src}\nreturn module.exports;\n})({ exports: {} }, __req);\n`;
}
js += `
const KEY = 'count-snapshots-v1';
let saved = [];
try { saved = JSON.parse(localStorage.getItem(KEY) || '[]'); } catch { /* storage unavailable */ }
window.Backend = __mods.core.createCore({
  base: ${base},
  snapshots: saved,
  saveSnapshot: (snap, all) => { try { localStorage.setItem(KEY, JSON.stringify(all.slice(-800))); } catch { /* ignore */ } },
});
})();
`;
fs.writeFileSync(path.join(out, 'backend.js'), js);
const html = path.join(out, 'index.html');
fs.writeFileSync(html, fs.readFileSync(html, 'utf8').replace('<script src="app.js"></script>', '<script src="backend.js"></script>\n<script src="app.js"></script>'));
console.log('built docs/', fs.readdirSync(out));
